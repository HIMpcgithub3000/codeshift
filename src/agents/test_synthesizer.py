class JUnitMockitoParser:
    """Parses Java JUnit and Mockito test files into structured representations."""

    @classmethod
    def parse_test_file(cls, file_path: str) -> Dict[str, Any]:
        with open(file_path, "r", encoding="utf-8") as f:
            code = f.read()

        class_match = re.search(r'public\s+class\s+(\w+)', code)
        class_name = class_match.group(1) if class_match else os.path.basename(file_path).replace(".java", "")

        # Extract mock fields
        mocks = []
        for mm in re.finditer(r'@Mock(?:Bean)?\s+(?:private\s+)?(\w+)\s+(\w+);', code):
            mocks.append({"type": mm.group(1), "name": mm.group(2)})

        # Extract test methods
        methods = []
        test_method_matches = re.finditer(r'@Test\s*(?:@DisplayName\s*\(\s*["\']([^"\']+)["\']\s*\))?\s*void\s+(\w+)\s*\(\s*\)\s*\{([^}]+)\}', code, re.DOTALL)
        for tm in test_method_matches:
            display_name = tm.group(1) or tm.group(2)
            method_name = tm.group(2)
            body = tm.group(3)

            # Count assertions and mocks in body
            assert_count = len(re.findall(r'assert\w+\(', body))
            mock_count = len(re.findall(r'(?:when|verify)\(', body))

            methods.append({
                "method_name": method_name,
                "display_name": display_name,
                "body": body.strip(),
                "assert_count": max(assert_count, 1),
                "mock_count": mock_count
            })

        return {
            "class_name": class_name,
            "source_file": os.path.basename(file_path),
            "mocks": mocks,
            "methods": methods
        }


